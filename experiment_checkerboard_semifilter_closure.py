"""Check whether checkerboard pairs cover every anchored semi-filter.

The product checkerboard theorem covers the minimal filter generated by an
anchor's coordinate slices. This script uses preservation closure to test the
stronger quantifier from cover complexity: does the same pair list force the
empty set into every semi-filter above each anchor?
"""

from __future__ import annotations

from itertools import product


def test(q: int, n: int, anchors: list[tuple[int, ...]]) -> None:
    full_product = list(product(range(q), repeat=n))
    universe = [x for x in full_product if x not in set(anchors)]
    point_index = {x: i for i, x in enumerate(universe)}
    split = q // 2
    r, rb = set(range(split)), set(range(split, q))
    c, cb = set(range(split)), set(range(split, q))

    def encode(xs):
        return sum(1 << point_index[x] for x in xs)

    e1 = encode(x for x in universe if x[0] in r or x[1] in c)
    h1 = encode(x for x in universe if x[0] in rb or x[1] in cb)
    e2 = encode(x for x in universe if x[0] in r or x[1] in cb)
    h2 = encode(x for x in universe if x[0] in rb or x[1] in c)
    pairs = [(e1, h1), (e2, h2)]
    all_subsets = range(1 << len(universe))
    bad = []

    for a in anchors:
        generators = [encode(x for x in universe if x[i] == a[i]) for i in range(n)]
        assert all(generators), f"anchor {a} has an empty required slice"
        closure = set()
        for g in generators:
            closure.update(s for s in all_subsets if s & g == g)
        rounds = 0
        while True:
            rounds += 1
            additions = set()
            for e, h in pairs:
                if e in closure and h in closure:
                    additions.update(s for s in all_subsets if s & (e & h) == (e & h))
            new = additions - closure
            if not new:
                break
            closure.update(new)
            if 0 in closure:
                break
        if 0 not in closure:
            minimal = [s for s in closure
                       if not any(t != s and t & s == t for t in closure)]
            bad.append((a, len(closure), [
                [universe[i] for i in range(len(universe)) if s >> i & 1]
                for s in minimal
            ]))

    print(f"q={q}; n={n}; universe={len(universe)}; anchors={len(anchors)}; pairs=2; anchors_with_preserving_semifilter={len(bad)}")
    if bad:
        a, size, mins = bad[0]
        print(f"  witness_anchor={a}; closure_size={size}; minimal_members={mins}")
    else:
        print("  closure reaches empty for every anchor")


def main() -> None:
    test(2, 4, [(0, 0, 0, 0), (1, 1, 1, 1)])


if __name__ == "__main__":
    main()
