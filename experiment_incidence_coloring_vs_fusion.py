"""Compare weak line-hypergraph coloring with exact fusion cover on small planes.

For a finite incidence plane, each anchor filter is generated by all lines
through that point. The script exhausts every endpoint pair, computes the exact
minimum number of fusion profiles covering all anchors, and independently
searches the minimum number of colors needed so no line is monochromatic.
Only small planes are intended; this is a structural diagnostic, not a theorem.
"""

from __future__ import annotations

from itertools import product

import numpy as np


def normalize(vector, q):
    first = next(x for x in vector if x)
    inverse = next(y for y in range(q) if first * y % q == 1)
    return tuple(x * inverse % q for x in vector)


def projective_plane(q):
    points = sorted({normalize(v, q) for v in product(range(q), repeat=3) if any(v)})
    lines = set()
    for raw in product(range(q), repeat=3):
        if not any(raw):
            continue
        normal = normalize(raw, q)
        line = frozenset(i for i, p in enumerate(points)
                         if sum(a * b for a, b in zip(normal, p)) % q == 0)
        lines.add(line)
    return points, sorted(lines, key=lambda x: tuple(sorted(x)))


def affine_plane(q):
    points = list(product(range(q), repeat=2))
    directions = {normalize(v, q) for v in product(range(q), repeat=2) if any(v)}
    lines = set()
    for a, b in directions:
        for c in range(q):
            line = frozenset(i for i, (x, y) in enumerate(points)
                             if (a * x + b * y) % q == c)
            lines.add(line)
    return points, sorted(lines, key=lambda x: tuple(sorted(x)))


def exact_fusion_cover(points, lines):
    n = len(points)
    endpoint_count = 1 << n
    line_masks = [sum(1 << i for i in line) for line in lines]
    incident = [tuple(mask for mask in line_masks if mask >> a & 1) for a in range(n)]
    endpoints = np.arange(endpoint_count, dtype=np.uint32)
    accepted = []
    for a in range(n):
        ok = np.zeros(endpoint_count, dtype=np.bool_)
        for line in incident[a]:
            ok |= (np.bitwise_and(endpoints, line) == line)
        accepted.append(ok)
    codes = np.zeros(endpoint_count * endpoint_count, dtype=np.uint16)
    block = 128
    for a, ok in enumerate(accepted):
        for lo in range(0, endpoint_count, block):
            hi = min(lo + block, endpoint_count)
            left = endpoints[lo:hi]
            common = np.bitwise_and(left[:, None], endpoints[None, :])
            covers = ok[left, None] & ok[None, :] & ~ok[common]
            start, stop = lo * endpoint_count, hi * endpoint_count
            codes[start:stop] |= covers.ravel().astype(np.uint16) * np.uint16(1 << a)
    profiles = np.unique(codes)
    profiles = profiles[profiles != 0].astype(np.uint32)
    max_profile = max(int(profile).bit_count() for profile in profiles)

    state_count = 1 << n
    dp = np.full(state_count, n + 1, dtype=np.int16)
    dp[0] = 0
    states = np.arange(state_count, dtype=np.uint32)
    for profile in profiles:
        old = dp.copy()
        np.minimum.at(dp, np.bitwise_or(states, profile), old + 1)
    return int(dp[-1]), max_profile, len(profiles)


def weak_chromatic_number(point_count, lines):
    for colors in range(2, point_count + 1):
        for coloring in product(range(colors), repeat=point_count):
            if all(len({coloring[p] for p in line}) >= 2 for line in lines):
                return colors, coloring
    raise AssertionError("coloring with point_count colors always exists")


def main():
    cases = [
        ("PG(2,2)", projective_plane(2)),
        ("PG(2,3)", projective_plane(3)),
        ("AG(2,2)", affine_plane(2)),
        ("AG(2,3)", affine_plane(3)),
    ]
    for name, (points, lines) in cases:
        cover, max_profile, profile_count = exact_fusion_cover(points, lines)
        chromatic, coloring = weak_chromatic_number(len(points), lines)
        print(f"{name}: points={len(points)}; lines={len(lines)}; fusion_cover={cover}; weak_chromatic_number={chromatic}; max_profile={max_profile}/{len(points)}; profiles={profile_count}")
        print(f"  weak_coloring={tuple(coloring)}")


if __name__ == "__main__":
    main()
