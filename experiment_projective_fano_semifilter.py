"""Exact pilot for nonlinear projective incidence filters on the Fano plane.

Each of the seven nonzero vectors in GF(2)^3 is both a point and an anchor.
For anchor a, the upward filter is generated by its three matching coordinate
slices and by every projective line through a.  All 128 endpoint subsets and
all ordered endpoint pairs are checked exactly.  This is a finite diagnostic,
not an asymptotic or P-vs-NP result.
"""

from __future__ import annotations

from itertools import combinations
import sys


POINTS = tuple(range(1, 8))
POINT_INDEX = {point: i for i, point in enumerate(POINTS)}
ANCHORS = POINTS
ENDPOINTS = range(1 << len(POINTS))
TARGET = (1 << len(ANCHORS)) - 1


def point_set_mask(points):
    return sum(1 << POINT_INDEX[p] for p in points)


LINES = {
    point_set_mask((x, y, x ^ y))
    for x, y in combinations(POINTS, 2)
}


def literal_masks(anchor):
    return [
        point_set_mask(p for p in POINTS if ((p >> bit) & 1) == ((anchor >> bit) & 1))
        for bit in range(3)
    ]


def minimal_generators(anchor, mode="combined"):
    raw = set()
    if mode in ("combined", "coordinates"):
        raw.update(literal_masks(anchor))
    if mode in ("combined", "lines"):
        raw.update(line for line in LINES if line >> POINT_INDEX[anchor] & 1)
    return tuple(g for g in raw if not any(h != g and h & g == h for h in raw))


def accepts(endpoint, generators):
    return any(endpoint & g == g for g in generators)


def main(mode="combined"):
    endpoint_pairs = [(e, h, e & h) for e in ENDPOINTS for h in ENDPOINTS]
    cover_codes = [0] * len(endpoint_pairs)
    per_anchor_masks = []
    for ai, anchor in enumerate(ANCHORS):
        generators = minimal_generators(anchor, mode)
        accepted = [accepts(e, generators) for e in ENDPOINTS]
        masks = set()
        for pair_index, (e, h, common) in enumerate(endpoint_pairs):
            if accepted[e] and accepted[h] and not accepted[common]:
                cover_codes[pair_index] |= 1 << ai
                masks.add(1 << ai)
        per_anchor_masks.append(masks)

    attainable = sorted(set(cover_codes) - {0})
    maximum = max(mask.bit_count() for mask in attainable)
    dp = {0: 0}
    parent = {}
    for mask in attainable:
        for old, count in list(dp.items()):
            new = old | mask
            if new not in dp or dp[new] > count + 1:
                dp[new] = count + 1
                parent[new] = (old, mask)
    print(f"mode={mode}; points={len(POINTS)}; anchors={len(ANCHORS)}; lines={len(LINES)}; endpoint_pairs={len(endpoint_pairs)}")
    print(f"minimal_generator_counts={[len(minimal_generators(a, mode)) for a in ANCHORS]}")
    print(f"distinct_nonzero_coverage_masks={len(attainable)}; max_single_pair_coverage={maximum}/{len(ANCHORS)}; exact_cover_number={dp.get(TARGET)}")
    if TARGET in dp:
        selected = []
        cursor = TARGET
        while cursor:
            old, mask = parent[cursor]
            selected.append(mask)
            cursor = old
        for mask in selected:
            pair_index = cover_codes.index(mask)
            e, h, common = endpoint_pairs[pair_index]
            covered = [ANCHORS[i] for i in range(len(ANCHORS)) if mask >> i & 1]
            fmt = lambda s: [POINTS[i] for i in range(len(POINTS)) if s >> i & 1]
            print(f"  E={fmt(e)}; H={fmt(h)}; E_inter_H={fmt(common)}; covered_anchors={covered}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "combined")
