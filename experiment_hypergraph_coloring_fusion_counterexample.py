"""Exact counterexample to identifying fusion cover with weak coloring.

The 3-uniform hypergraph has five vertices and edges 012, 124, 023, 123,
and 024. It is weakly 2-colorable by coloring vertex 2 red and every other
vertex blue. For each anchor, its filter is generated by all incident edges.
All 32 endpoint subsets and all 1,024 ordered pairs are checked exactly.
"""

from __future__ import annotations

from itertools import combinations_with_replacement, product


N = 5
EDGES = ((0, 1, 2), (1, 2, 4), (0, 2, 3), (1, 2, 3), (0, 2, 4))
GENERATORS = [
    [sum(1 << v for v in edge) for edge in EDGES if anchor in edge]
    for anchor in range(N)
]
ENDPOINTS = range(1 << N)
TARGET = (1 << N) - 1


def accepted(anchor, endpoint):
    return any(endpoint & witness == witness for witness in GENERATORS[anchor])


def main():
    profiles = set()
    example = {}
    for left in ENDPOINTS:
        for right in ENDPOINTS:
            common = left & right
            profile = 0
            for anchor in range(N):
                if (accepted(anchor, left) and accepted(anchor, right)
                        and not accepted(anchor, common)):
                    profile |= 1 << anchor
            if profile:
                profiles.add(profile)
                example.setdefault(profile, (left, right))

    dp = {0: 0}
    parent = {}
    for profile in profiles:
        for covered, count in list(dp.items()):
            union = covered | profile
            if union not in dp or dp[union] > count + 1:
                dp[union] = count + 1
                parent[union] = (covered, profile)

    assert set().union(*(set(a for a in range(N) if p >> a & 1)
                         for p in profiles)) == set(range(N))
    coloring = (1, 1, 0, 1, 1)
    assert all(len({coloring[v] for v in edge}) >= 2 for edge in EDGES)
    assert dp[TARGET] == 3
    assert not any(a | b == TARGET for a, b in combinations_with_replacement(profiles, 2))

    dual_coloring = None
    for colors in product(range(2), repeat=len(EDGES)):
        if all(len({colors[j] for j, edge in enumerate(EDGES) if anchor in edge}) == 2
               for anchor in range(N)):
            dual_coloring = colors
            break
    assert dual_coloring is not None
    red = sum(1 << v for v in range(N)
              if any(dual_coloring[j] == 0 and v in edge
                     for j, edge in enumerate(EDGES)))
    blue = sum(1 << v for v in range(N)
               if any(dual_coloring[j] == 1 and v in edge
                      for j, edge in enumerate(EDGES)))
    overlap = red & blue
    contaminated = [edge for edge in EDGES
                    if all(overlap >> v & 1 for v in edge)]
    assert contaminated

    selected = []
    state = TARGET
    while state:
        previous, profile = parent[state]
        selected.append(profile)
        state = previous

    fmt = lambda mask: [v for v in range(N) if mask >> v & 1]
    print(f"vertices={N}; hyperedges={EDGES}; incident_generator_counts={[len(g) for g in GENERATORS]}")
    print(f"weak_chromatic_number=2 (coloring={coloring}); profiles={len(profiles)}; max_profile_size={max(p.bit_count() for p in profiles)}; exact_fusion_cover=3")
    print(f"dual_weak_2_coloring={dual_coloring}; red_shadow={fmt(red)}; blue_shadow={fmt(blue)}; overlap={fmt(overlap)}; overlap_contaminating_edges={contaminated}")
    print("one- and two-profile covers: none; three-profile certificate:")
    for profile in selected:
        left, right = example[profile]
        print(f"  profile={fmt(profile)}; E={fmt(left)}; H={fmt(right)}; intersection={fmt(left & right)}")


if __name__ == "__main__":
    main()
