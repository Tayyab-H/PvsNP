"""Exact tests of the chromatic lower bound for incident-edge filters.

For graph G on vertex universe U, anchor v has a filter generated by every
edge incident to v. Every fusion profile is an independent set, so its cover
number is at least chi(G). This script exactly checks small examples and the
clique equality case; it does not address the project-level embedding gap.
"""

from __future__ import annotations

from itertools import combinations, product


def analyze(name, n, edges):
    edge_masks = [sum(1 << v for v in edge) for edge in edges]
    generators = [[e for e in edge_masks if e >> a & 1] for a in range(n)]
    endpoints = range(1 << n)
    accepted = [[any(s & e == e for e in generators[a])
                 for s in endpoints] for a in range(n)]

    profiles = set()
    for left in endpoints:
        for right in endpoints:
            common = left & right
            profile = 0
            for a in range(n):
                if accepted[a][left] and accepted[a][right] and not accepted[a][common]:
                    profile |= 1 << a
            if profile:
                assert all(profile & edge != edge for edge in edge_masks)
                profiles.add(profile)

    target = (1 << n) - 1
    dp = [n + 1] * (target + 1)
    dp[0] = 0
    for profile in profiles:
        old = dp[:]
        for covered, count in enumerate(old):
            dp[covered | profile] = min(dp[covered | profile], count + 1)

    chi = n
    for colors in range(1, n + 1):
        if any(all(len({coloring[v] for v in edge}) >= 2 for edge in edges)
               for coloring in product(range(colors), repeat=n)):
            chi = colors
            break
    assert all(profile.bit_count() <= n for profile in profiles)
    if min(map(len, generators)) >= 2:
        assert (sum(1 << i for i in range(n) if any(p >> i & 1 for p in profiles))
                == target)
    print(f"{name}: vertices={n}; edges={len(edges)}; min_degree={min(map(len,generators))}; chi={chi}; exact_fusion_cover={dp[target]}; profiles={len(profiles)}; max_profile={max(p.bit_count() for p in profiles)}/{n}")


def main():
    analyze("K5", 5, list(combinations(range(5), 2)))
    analyze("C5", 5, [(0, 1), (1, 2), (2, 3), (3, 4), (4, 0)])
    analyze("K2,3", 5, [(i, j) for i in range(2) for j in range(2, 5)])
    analyze("C6", 6, [(i, (i + 1) % 6) for i in range(6)])


if __name__ == "__main__":
    main()
