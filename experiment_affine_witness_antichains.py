"""Exact toy search for affine-subspace witnesses inside anchor literals.

Each semi-filter is generated by one random affine slice inside each literal
generator. All endpoint pairs are enumerated on a 4-bit promise. This checks
whether this small structured variant evades the same easy covers; it does
not support an asymptotic claim.
"""

import random


N = 4
U_WORDS = [word for word in range(1 << N) if word.bit_count() >= 2]
ANCHORS = [word for word in range(1 << N) if word.bit_count() <= 1]
SET_COUNT = 1 << len(U_WORDS)
TARGET = (1 << len(ANCHORS)) - 1
TRIALS = 20
SEED = 20260925


def affine_certificate(anchor, coordinate, equation_mask, parity_value):
    return sum(
        1 << index
        for index, word in enumerate(U_WORDS)
        if ((word >> coordinate) & 1) == ((anchor >> coordinate) & 1)
        and ((word & equation_mask).bit_count() % 2) == parity_value
    )


def minimal_antichain(certificates):
    unique = set(certificates)
    return [
        cert for cert in unique
        if not any(other != cert and (other & cert) == other
                   for other in unique)
    ]


def exact_cover_size(cover_masks):
    reachable = {0}
    for depth in range(1, len(ANCHORS) + 1):
        next_reachable = {
            old | cover
            for old in reachable
            for cover in cover_masks
        }
        if TARGET in next_reachable:
            return depth
        reachable |= next_reachable
    return None


def one_trial(rng):
    certificates = []
    for anchor in ANCHORS:
        row = []
        for coordinate in range(N):
            masks = [
                mask for mask in range(1, 1 << N)
                if mask.bit_count() >= 2
            ]
            rng.shuffle(masks)
            cert = 0
            for mask in masks:
                value = rng.randrange(2)
                cert = affine_certificate(anchor, coordinate, mask, value)
                if cert:
                    break
                cert = affine_certificate(anchor, coordinate, mask, 1 - value)
                if cert:
                    break
            assert cert
            row.append(cert)
        certificates.append(minimal_antichain(row))

    # membership[W] is the bitset of filters containing W.
    membership = [0] * SET_COUNT
    for anchor_index, row in enumerate(certificates):
        anchor_bit = 1 << anchor_index
        for subset in range(SET_COUNT):
            if any((subset & cert) == cert for cert in row):
                membership[subset] |= anchor_bit

    cover_masks = set()
    max_pair_coverage = 0
    full_covering_pair = None
    for left in range(SET_COUNT):
        left_members = membership[left]
        if not left_members:
            continue
        for right in range(SET_COUNT):
            covered = left_members & membership[right] & ~membership[left & right]
            covered &= TARGET
            if covered:
                cover_masks.add(covered)
                max_pair_coverage = max(
                    max_pair_coverage, covered.bit_count()
                )
                if covered == TARGET and full_covering_pair is None:
                    full_covering_pair = (left, right)

    return exact_cover_size(cover_masks), max_pair_coverage, full_covering_pair


def main():
    rng = random.Random(SEED)
    histogram = {}
    max_cover = 0
    min_max_pair = len(ANCHORS)
    sample_pair = None
    for _ in range(TRIALS):
        cover, pair_coverage, full_pair = one_trial(rng)
        histogram[cover] = histogram.get(cover, 0) + 1
        max_cover = max(max_cover, cover)
        min_max_pair = min(min_max_pair, pair_coverage)
        if sample_pair is None:
            sample_pair = full_pair

    print(
        f"TRIALS={TRIALS}; N={N}; |U|={len(U_WORDS)}; "
        f"anchors={len(ANCHORS)}; seed={SEED}"
    )
    print(f"exact_cover_size_histogram={dict(sorted(histogram.items()))}")
    print(f"largest_cover_size_seen={max_cover}")
    print(f"smallest_max_pair_coverage_seen={min_max_pair}/{len(ANCHORS)}")
    print(
        "first_trial_full_pair="
        + str(tuple(
            [format(U_WORDS[i], f"0{N}b")
             for i in range(len(U_WORDS)) if mask & (1 << i)]
            for mask in sample_pair
        ))
    )


if __name__ == "__main__":
    main()
