"""Exact 13-anchor test of projective incidence filters over GF(3).

Points and lines of PG(2,3) are represented by normalized nonzero vectors.
For each anchor, the filter is generated by its three coordinate-value slices
and all incident projective lines. Every endpoint subset and every ordered
endpoint pair are checked. The search tests whether the exact cover is at
most three; any reported cover-two or cover-three certificate is explicit.
This is a finite pilot, not an asymptotic result.
"""

from __future__ import annotations

from itertools import product
import sys

import numpy as np


Q = 3


def normalize(vector):
    first = next(x for x in vector if x)
    inverse = next(y for y in range(Q) if first * y % Q == 1)
    return tuple(x * inverse % Q for x in vector)


POINTS = sorted({normalize(v) for v in product(range(Q), repeat=3) if any(v)})
POINT_INDEX = {p: i for i, p in enumerate(POINTS)}
ANCHORS = POINTS
M = len(POINTS)
ENDPOINT_COUNT = 1 << M
PAIR_COUNT = ENDPOINT_COUNT * ENDPOINT_COUNT
TARGET = (1 << len(ANCHORS)) - 1


def mask_of(indices):
    return sum(1 << i for i in indices)


LINE_MASKS = {
    mask_of(i for i, point in enumerate(POINTS)
            if sum(a * b for a, b in zip(normal, point)) % Q == 0)
    for raw in product(range(Q), repeat=3) if any(raw)
    for normal in (normalize(raw),)
}


def minimal_generators(anchor, mode="combined"):
    raw = set()
    if mode in ("combined", "coordinates"):
        for coordinate, value in enumerate(anchor):
            raw.add(mask_of(i for i, point in enumerate(POINTS)
                            if point[coordinate] == value))
    if mode in ("combined", "lines"):
        raw.update(line for line in LINE_MASKS if line >> POINT_INDEX[anchor] & 1)
    return tuple(g for g in raw if not any(h != g and h & g == h for h in raw))


def superset_table(masks):
    has = np.zeros(1 << len(ANCHORS), dtype=np.bool_)
    has[masks] = True
    all_masks = np.arange(len(has), dtype=np.uint32)
    for bit in range(len(ANCHORS)):
        no_bit = all_masks[(all_masks & (1 << bit)) == 0]
        has[no_bit] |= has[no_bit | (1 << bit)]
    return has


def pair_for_mask(codes, code):
    flat = int(np.flatnonzero(codes == code)[0])
    return flat // ENDPOINT_COUNT, flat % ENDPOINT_COUNT


def endpoint_points(mask):
    return [POINTS[i] for i in range(M) if mask >> i & 1]


def main(mode="combined"):
    endpoints = np.arange(ENDPOINT_COUNT, dtype=np.uint32)
    codes = np.zeros(PAIR_COUNT, dtype=np.uint16)
    block = 128
    gen_counts = []
    for anchor_index, anchor in enumerate(ANCHORS):
        generators = minimal_generators(anchor, mode)
        gen_counts.append(len(generators))
        accepted = np.zeros(ENDPOINT_COUNT, dtype=np.bool_)
        for generator in generators:
            accepted |= (np.bitwise_and(endpoints, generator) == generator)
        bit = np.uint16(1 << anchor_index)
        for lo in range(0, ENDPOINT_COUNT, block):
            hi = min(lo + block, ENDPOINT_COUNT)
            left = endpoints[lo:hi]
            common = np.bitwise_and(left[:, None], endpoints[None, :])
            covers = (accepted[left, None] & accepted[None, :]
                      & ~accepted[common])
            start = lo * ENDPOINT_COUNT
            stop = hi * ENDPOINT_COUNT
            codes[start:stop] |= covers.ravel().astype(np.uint16) * bit

    unique, first = np.unique(codes, return_index=True)
    keep = unique != 0
    masks = unique[keep].astype(np.uint32)
    first_by_mask = {int(mask): int(i) for mask, i in zip(unique[keep], first[keep])}
    max_coverage = max(int(mask).bit_count() for mask in masks)
    has = superset_table(masks)

    single_cover = TARGET in set(int(mask) for mask in masks)
    pair_cover = None
    if not single_cover:
        for mask in masks:
            missing = TARGET ^ int(mask)
            if has[missing]:
                second = next(int(candidate) for candidate in masks
                              if int(candidate) & missing == missing)
                pair_cover = (int(mask), second)
                break

    triple_cover = None
    if pair_cover is None and not single_cover:
        for first_mask in masks:
            unions = np.bitwise_or(masks, first_mask)
            for second_union in np.unique(unions):
                missing = TARGET ^ int(second_union)
                if has[missing]:
                    third = next(int(candidate) for candidate in masks
                                 if int(candidate) & missing == missing)
                    second = next(int(candidate) for candidate in masks
                                  if int(candidate) | int(first_mask) == int(second_union))
                    triple_cover = (int(first_mask), second, third)
                    break
            if triple_cover is not None:
                break

    print(f"mode={mode}; field=GF({Q}); points={M}; anchors={len(ANCHORS)}; lines={len(LINE_MASKS)}; endpoint_pairs={PAIR_COUNT}")
    print(f"minimal_generator_counts={gen_counts}; distinct_nonzero_coverage_masks={len(masks)}; max_single_pair_coverage={max_coverage}/{len(ANCHORS)}")
    if single_cover:
        print("exact_cover_number=1")
        selected = (TARGET,)
    elif pair_cover is not None:
        print("exact_cover_number=2 (one pair was separately checked absent)")
        selected = pair_cover
    elif triple_cover is not None:
        print("exact_cover_number=3 (one and two pairs were separately checked absent)")
        selected = triple_cover
    else:
        print("no cover of size at most three found; this is not a proof of a larger exact value")
        return

    for coverage_mask in selected:
        flat = first_by_mask[coverage_mask]
        left = flat // ENDPOINT_COUNT
        right = flat % ENDPOINT_COUNT
        covered = [ANCHORS[i] for i in range(len(ANCHORS))
                   if coverage_mask >> i & 1]
        common = left & right
        print(f"  E={endpoint_points(left)}; H={endpoint_points(right)}; E_inter_H={endpoint_points(common)}; covered_anchors={covered}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "combined")
